package dev.vhdltoolkit.run

import java.nio.file.Path
import kotlin.io.path.isRegularFile

/** What a run configuration asks Vivado to do. */
enum class VivadoAction(val displayName: String) {
    SYNTHESIS("Synthesis"),
    IMPLEMENTATION("Implementation"),
    BITSTREAM("Generate bitstream"),
    SIMULATION("Simulate (XSim)"),
    ;

    companion object {
        fun from(name: String?): VivadoAction =
            entries.firstOrNull { it.name == name } ?: SYNTHESIS
    }
}

/**
 * Generates the Tcl that drives Vivado in batch mode.
 *
 * Batch Vivado does not fail on a failed run: `launch_runs` returns as soon as
 * the job is queued and a synthesis error leaves the process exiting zero. So
 * each stage explicitly checks the run's status afterwards and exits non-zero,
 * otherwise the IDE would report success over a broken build.
 */
object VivadoTcl {

    fun script(xpr: Path, action: VivadoAction, jobs: Int): String {
        val project = tcl(xpr.toString())
        val j = jobs.coerceIn(1, 64)

        return buildString {
            appendLine("# Generated by VHDL Toolkit.")
            appendLine("open_project $project")
            appendLine()

            when (action) {
                VivadoAction.SYNTHESIS -> {
                    appendRun("synth_1", j)
                }

                VivadoAction.IMPLEMENTATION -> {
                    appendRun("synth_1", j)
                    appendRun("impl_1", j)
                }

                VivadoAction.BITSTREAM -> {
                    appendRun("synth_1", j)
                    appendRun("impl_1", j, toStep = "write_bitstream")
                    appendLine("""puts "VHDL Toolkit: bitstream written to [get_property DIRECTORY [get_runs impl_1]]"""")
                }

                VivadoAction.SIMULATION -> {
                    appendLine("launch_simulation")
                    appendLine("run all")
                }
            }

            appendLine()
            appendLine("exit 0")
        }
    }

    private fun StringBuilder.appendRun(run: String, jobs: Int, toStep: String? = null) {
        val step = if (toStep != null) " -to_step $toStep" else ""
        appendLine("reset_run $run")
        appendLine("launch_runs $run$step -jobs $jobs")
        appendLine("wait_on_run $run")
        // PROGRESS is the reliable signal: STATUS text varies by version.
        appendLine("if {[get_property PROGRESS [get_runs $run]] != \"100%\"} {")
        appendLine("""    puts "ERROR: VHDL Toolkit: $run did not complete ([get_property STATUS [get_runs $run]])"""")
        appendLine("    exit 1")
        appendLine("}")
        appendLine()
    }

    /** Braces are Tcl's literal quoting, which suits paths containing spaces. */
    private fun tcl(value: String): String =
        if (value.none { it in "{}\\" }) "{$value}" else "\"${value.replace("\\", "\\\\").replace("\"", "\\\"")}\""
}

/**
 * Finds the `vivado` launcher inside an installation.
 *
 * Which installation is a question for the IDE side, where the setting and
 * the user's shell environment live; see `VivadoLocator.executable`.
 */
object VivadoExecutable {

    fun forInstall(install: Path): Path? {
        val candidates = listOf("bin/vivado", "bin/vivado.bat")
        return candidates.map { install.resolve(it) }.firstOrNull { it.isRegularFile() }
    }
}
