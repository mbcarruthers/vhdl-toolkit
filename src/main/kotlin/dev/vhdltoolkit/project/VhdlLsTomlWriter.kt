package dev.vhdltoolkit.project

import java.nio.file.Path

/**
 * Renders a [LibraryMappingModel] as a `vhdl_ls.toml`.
 *
 * Paths are written relative to the toml's own directory where possible, since
 * VHDL-LS resolves them against that directory and relative paths keep the file
 * portable between machines and checkouts.
 */
object VhdlLsTomlWriter {

    const val GENERATED_MARKER = "# Generated by VHDL Toolkit."

    /**
     * @param model     the mapping to write
     * @param tomlDir   directory the toml will live in; paths are relativized to it
     */
    fun render(model: LibraryMappingModel, tomlDir: Path): String {
        val m = model.normalized()
        val sb = StringBuilder()

        sb.appendLine(GENERATED_MARKER)
        sb.appendLine("# Source: ${m.source}")
        sb.appendLine("# Edits to this file are replaced when it is regenerated.")
        sb.appendLine()

        if (m.warnings.isNotEmpty()) {
            for (w in m.warnings) sb.appendLine("# NOTE: ${w.message}")
            sb.appendLine()
        }

        m.standard?.let {
            sb.appendLine("standard = ${quote(it)}")
            sb.appendLine()
        }

        if (m.libraries.isEmpty()) {
            sb.appendLine("# No VHDL sources were found.")
            sb.appendLine("[libraries]")
            return sb.toString()
        }

        sb.appendLine("[libraries]")
        for (lib in m.libraries) {
            val name = LibraryNames.sanitize(lib.name)
            sb.appendLine()
            sb.appendLine("${name}.files = [")
            for (f in lib.files) {
                sb.appendLine("    ${quote(relativize(f, tomlDir))},")
            }
            sb.appendLine("]")
            if (lib.isThirdParty) {
                sb.appendLine("${name}.is_third_party = true")
            }
        }
        return sb.toString()
    }

    /**
     * Relative where the file sits under [tomlDir], absolute otherwise. Vendor
     * libraries typically live outside the project, so both cases are normal.
     */
    private fun relativize(file: Path, tomlDir: Path): String {
        val f = file.normalize()
        val d = tomlDir.normalize()
        val rel = runCatching { d.relativize(f) }.getOrNull()
        val text = if (rel != null && !rel.startsWith("..")) rel.toString() else f.toString()
        // TOML and VHDL-LS both accept forward slashes on every platform.
        return text.replace('\\', '/')
    }

    /**
     * Single quotes are TOML literal strings: no escape processing, which suits
     * Windows paths. Falls back to a basic string if the path contains a quote.
     */
    private fun quote(value: String): String =
        if (!value.contains('\'')) "'$value'" else "\"${value.replace("\\", "\\\\").replace("\"", "\\\"")}\""
}
