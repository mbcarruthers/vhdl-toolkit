package dev.vhdltoolkit.project

import com.intellij.notification.NotificationGroupManager
import com.intellij.notification.NotificationType
import com.intellij.openapi.actionSystem.ActionUpdateThread
import com.intellij.openapi.actionSystem.AnAction
import com.intellij.openapi.actionSystem.AnActionEvent
import com.intellij.openapi.application.ApplicationManager
import com.intellij.openapi.ui.Messages

/**
 * Tools | Sync VHDL Library Mapping — regenerates `vhdl_ls.toml` from the
 * project's own description on demand, for when a source file has been added
 * in Vivado and the mapping needs to catch up.
 */
class SyncVhdlMappingAction : AnAction() {

    override fun getActionUpdateThread(): ActionUpdateThread = ActionUpdateThread.BGT

    override fun update(e: AnActionEvent) {
        e.presentation.isEnabledAndVisible = e.project != null
    }

    override fun actionPerformed(e: AnActionEvent) {
        val project = e.project ?: return
        val service = VhdlMappingService.getInstance(project)

        val source = service.detectSource()
        if (source == null) {
            NotificationGroupManager.getInstance()
                .getNotificationGroup("VHDL Toolkit")
                .createNotification(
                    "No importable project found",
                    "Looked for a Vivado .xpr, a project Tcl script, an HDL file list and " +
                        "any VHDL sources under the project root, and found none. Open the " +
                        "directory containing your design as the project root.",
                    NotificationType.WARNING,
                )
                .notify(project)
            return
        }

        // Never silently clobber a mapping someone wrote themselves.
        if (service.tomlExists() && !service.existingTomlIsGenerated()) {
            val answer = Messages.showYesNoDialog(
                project,
                "${VhdlMappingService.TOML_NAME} was not generated by VHDL Toolkit and may contain " +
                    "settings that cannot be derived from ${source.label}.\n\nReplace it?",
                "Replace Existing ${VhdlMappingService.TOML_NAME}?",
                "Replace",
                "Cancel",
                Messages.getWarningIcon(),
            )
            if (answer != Messages.YES) return
        }

        ApplicationManager.getApplication().executeOnPooledThread {
            service.sync(source)
        }
    }
}
